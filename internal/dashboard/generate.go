//go:build ignore

// Run from the repository root after the dashboard build.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"slices"
)

func pack(w io.Writer) error {
	downloads, err := filepath.Glob("ui/public/assets/*")
	if err != nil {
		return err
	}
	entries, err := os.ReadDir("static/assets")
	if err != nil {
		return err
	}
	hashed := regexp.MustCompile(`^assets/[^/]+[-.][0-9a-fA-F]{8,}\.[a-zA-Z0-9]+$`)
	names := []string{"index.html", "birdwatch.js", "favicon.svg"}
	for _, e := range entries {
		name := e.Name()
		if e.Type().IsRegular() && (hashed.MatchString("assets/"+name) || name == "theme.js" || slices.Contains(downloads, filepath.Join("ui", "public", "assets", name))) {
			names = append(names, "assets/"+e.Name())
		}
	}
	tarball := tar.NewWriter(w)
	for _, name := range names {
		raw, err := os.ReadFile(filepath.Join("static", filepath.FromSlash(name)))
		if err != nil {
			return err
		}
		var encoded bytes.Buffer
		z := gzip.NewWriter(&encoded)
		if _, err = z.Write(raw); err != nil {
			return err
		}
		if err = z.Close(); err != nil {
			return err
		}
		header := tar.Header{Name: name, Mode: 0644, Size: int64(encoded.Len())}
		if hashed.MatchString(name) {
			header.PAXRecords = map[string]string{"BIRDWATCH.cache": "immutable"}
		}
		if err = tarball.WriteHeader(&header); err != nil {
			return err
		}
		if _, err = encoded.WriteTo(tarball); err != nil {
			return err
		}
	}
	return tarball.Close()
}

func generate() error {
	const dir = "internal/dashboard/generated by make dashboard"
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	f, err := os.CreateTemp(dir, ".assets-")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	err = pack(f)
	closeErr := f.Close()
	if err != nil {
		return err
	}
	if closeErr != nil {
		return closeErr
	}
	return os.Rename(f.Name(), filepath.Join(dir, "assets.tar"))
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, "Building embedded dashboard:", err)
		os.Exit(1)
	}
}
